function modernUzbek(text: string) {
  return text
    .replace(/sh/g, 'ş').replace(/Sh/g, 'Ş').replace(/SH/g, 'Ş')
    .replace(/ch/g, 'ç').replace(/Ch/g, 'Ç').replace(/CH/g, 'Ç')
    .replace(/g(?:ʻ|‘|')/g, 'ğ').replace(/G(?:ʻ|‘|')/g, 'Ğ')
    .replace(/o(?:ʻ|‘|')/g, 'ö').replace(/O(?:ʻ|‘|')/g, 'Ö')
}

interface LanguageContextValue { language: Language; setLanguage: (language: Language) => void; t: (text: string) => string }
const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = localStorage.getItem(STORAGE_KEY)
    return saved === 'ru' || saved === 'en' || saved === 'uz' ? saved : 'uz'
  })

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language)
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (text) => language === 'uz' ? modernUzbek(text) : (dictionaries[language][text] ?? text),
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage LanguageProvider ichida ishlatilishi kerak')
  return context
}
